"""Write a synthetic corpus to disk.

Layout::

    <out>/pdf/<doc_id>__<tag>.pdf     rendered document
    <out>/xml/<doc_id>__<tag>.xml     fiscal XML (part of the NF-e / NFS-e documents)
    <out>/truth/<doc_id>.json         ground truth (fields + layout + ``xml_filename``)
    <out>/manifest.json               generation parameters and type counts

Real mailboxes often carry the authorised XML next to the PDF, but not always:
``xml_share`` of the NF-e / NFS-e documents get one. The draw uses its own
random stream, so turning XMLs on or off never changes the PDFs.
"""

from __future__ import annotations

# Seeded `random` (B311) generates synthetic test data: reproducibility, not security.
import json
import random
from collections import Counter
from pathlib import Path
from typing import Any

from docai.synth.documents import make_document, sample_types
from docai.synth.names import company_pool
from docai.synth.render import render_document
from docai.synth.xml import XML_RENDERERS

DEFAULT_XML_SHARE = 0.6
GENERATOR_VERSION = 3  # bump when the documents change, so `docai demo` regenerates


def generate_corpus(
    n: int,
    out_dir: Path | str,
    *,
    seed: int = 42,
    prefix: str = "doc",
    mix: dict[str, float] | None = None,
    types: list[str] | None = None,
    xml_share: float = DEFAULT_XML_SHARE,
) -> list[dict[str, Any]]:
    """Generate ``n`` documents (or exactly ``types``) and return their ground truth."""
    out = Path(out_dir)
    for sub in ("pdf", "truth", "xml"):
        (out / sub).mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)  # nosec B311
    pool = company_pool(rng)
    doc_types = types if types is not None else sample_types(n, rng, mix)
    docs = []
    for i, doc_type in enumerate(doc_types, start=1):
        doc_id = f"{prefix}_{i:05d}"
        doc = make_document(doc_type, doc_id, rng, pool)
        render_document(doc, out / "pdf" / doc["filename"])
        doc["xml_filename"] = None
        xml_draw = random.Random(f"xml|{seed}|{doc_id}").random()  # nosec B311
        if doc_type in XML_RENDERERS and xml_draw < xml_share:
            doc["xml_filename"] = doc["filename"].removesuffix(".pdf") + ".xml"
            (out / "xml" / doc["xml_filename"]).write_bytes(XML_RENDERERS[doc_type](doc))
        (out / "truth" / f"{doc_id}.json").write_text(
            json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        docs.append(doc)
    manifest = {
        "n": len(docs),
        "seed": seed,
        "generator": GENERATOR_VERSION,
        "prefix": prefix,
        "counts": dict(sorted(Counter(d["doc_type"] for d in docs).items())),
        "with_xml": sum(1 for d in docs if d["xml_filename"]),
        "xml_share": xml_share,
        "note": "Synthetic documents generated by docai.synth; no real companies or records.",
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return docs
